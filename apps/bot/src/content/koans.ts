/** Карта дня: детерминирована парой (дата, пользователь). */
export function koanOfDay(telegramId: number | string, now = new Date()) {
  const index = pickForUser(koanLibrary, todayIsoDate(now), telegramId);
  return { index, entry: koanLibrary[index] };
}

export function koanByIndex(index: number): KoanEntry | undefined {
  return koanLibrary[index];
}
