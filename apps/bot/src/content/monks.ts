/** Монах дня: один на всех на дату — можно обсуждать с друзьями. */
export function monkOfDay(now = new Date()) {
  const index = pickByDate(monkLibrary, todayIsoDate(now), "monk");
  return { index, entry: monkLibrary[index] };
}

export function monkById(id: string): MonkEntry | undefined {
  return monkLibrary.find((monk) => monk.id === id);
}

/** Следующий по кругу — для кнопки «Другой монах». */
export function nextMonk(id: string): MonkEntry {
  const index = monkLibrary.findIndex((monk) => monk.id === id);
  return monkLibrary[(index + 1 + monkLibrary.length) % monkLibrary.length];
}
