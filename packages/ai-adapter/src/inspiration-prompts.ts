import type { AiInspirationRequest } from "./types";

/**
 * Промпты для «вдохновения» бота. Все три режима требуют смешного,
 * но уважительного тона: дзенский юмор, не карикатура.
 */
export function buildInspirationPrompt(request: AiInspirationRequest): string {
  const subject = request.subject ?? {};

  switch (request.kind) {
    case "koan":
      return [
        "Ты — генератор свежих дзенских коанов в духе Виктора Пелевина.",
        "Придумай ОДИН короткий коан (3–6 предложений) с абсурдно-бытовым сюжетом из современной жизни:",
        "метро, кофе, ноутбуки, совещания, доставка, смартфоны — и внезапная правда в конце.",
        "Правила: по-русски, без морали в лоб, без слова «коан» внутри текста, сухая подача без смайликов.",
        "Юмор — через абсурд ситуации, как у Пелевина, а не через шутки про политиков и не чёрный юмор.",
        "Ответь ТОЛЬКО текстом коана, без вступлений и кавычек.",
      ].join(" ");

    case "koan-commentary":
      return [
        "Ты — дзенский учитель, который с лёгкой иронией объясняет коан своему ученику.",
        "Вот коан и его источник:",
        `«${subject.text ?? ""}» (${subject.source ?? "традиция"}).`,
        "Дай толкование: 3–4 предложения, по-русски, тепло и с юмором, с примером из современной бытовой жизни (телефон, работа, пробки, чай).",
        "Без слов «как сказал бы дзенский учитель», без смайликов, без маркированных списков.",
        "Ответь только самим толкованием.",
      ].join(" ");

    case "monk-lesson":
      return [
        "Ты — наставник по практике. Расскажи, какой личный урок современный человек может вынести из подвига этого монаха:",
        `Имя: ${subject.name ?? ""}. Годы: ${subject.years ?? "неизвестны"}. Традиция: ${subject.tradition ?? ""}.`,
        `Подвиг: ${subject.feat ?? ""}.`,
        "Дай 2–3 предложения: конкретный, применимый сегодня совет, с лёгкой теплой иронией и без пафоса.",
        "Можно обыграть контраст между аскезой монаха и современной жизнью (у нас хотя бы отопление есть).",
        "По-русски, без смайликов, без списков. Ответь только самим уроком.",
      ].join(" ");

    default:
      throw new Error(`Unknown inspiration kind: ${request.kind}`);
  }
}
